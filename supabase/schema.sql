create or replace function public.is_family_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.family_members
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;


-- =====================================================================
-- Shortaxe — numéro court des opérations
-- =====================================================================
-- Ajoute à chaque opération un numéro entier unique (colonne ref), attribué
-- automatiquement à la création. Il est affiché devant le libellé des lignes
-- de budget (« #12 ») et dans la liste de choix des budgets.
-- Les opérations existantes sont numérotées par date de création.
-- Idempotente : peut être relancée sans erreur.

do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'transactions' and column_name = 'ref'
  ) then
    alter table public.transactions add column ref bigint;
    update public.transactions t
       set ref = s.n
      from (select id, row_number() over (order by created_at, id) as n from public.transactions) s
     where s.id = t.id;
    alter table public.transactions alter column ref set not null;
    alter table public.transactions alter column ref add generated by default as identity;
    perform setval(
      pg_get_serial_sequence('public.transactions', 'ref'),
      coalesce((select max(ref) from public.transactions), 0) + 1,
      false
    );
    alter table public.transactions add constraint transactions_ref_key unique (ref);
  end if;
end;
$$;
